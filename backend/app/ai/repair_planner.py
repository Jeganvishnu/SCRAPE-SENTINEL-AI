from typing import Dict, Any

class RepairPlanner:
    """
    Repair Planner with strict repair type allowlisting and boundary enforcement.
    Ensures AI proposals cannot execute arbitrary code or destructive operations.
    """

    ALLOWED_REPAIR_TYPES = {
        "selector_update",
        "field_mapping_update",
        "schema_mapping_update",
        "pagination_adjustment",
        "normalization_update",
        "retry_adjustment",
        "no_repair",
        "manual_review"
    }

    def generate_plan(self, provider_plan: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, Any]:
        repair_type = provider_plan.get("repair_type", "manual_review")

        # Strict allowlist check
        if repair_type not in self.ALLOWED_REPAIR_TYPES:
            return {
                "repair_type": "manual_review",
                "target": context.get("source_name", "target"),
                "changes": [],
                "reason": f"Disallowed repair type '{repair_type}' requested by AI. Rejected for safety.",
                "confidence": 0.0,
                "risk": "blocked",
                "verification_required": True,
                "allowed": False
            }

        return {
            "repair_type": repair_type,
            "target": provider_plan.get("target", context.get("source_name", "target")),
            "changes": provider_plan.get("changes", []),
            "reason": provider_plan.get("reason", "Automated repair plan generated by AI."),
            "confidence": float(provider_plan.get("confidence", 0.85)),
            "risk": provider_plan.get("risk", "low"),
            "verification_required": True,
            "allowed": True
        }

repair_planner = RepairPlanner()
